// @vitest-environment node
import fs from "node:fs";
import path from "node:path";
import { compile } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";
import { describe, expect, it } from "vitest";

const root = path.resolve(".");
const base = path.join(root, "src/styles");

async function prepare(css: string) {
  const compiler = await compile(css, {
    base,
    onDependency: () => undefined,
    shouldRewriteUrls: true,
  });
  let sources = compiler.sources;
  if (compiler.root === null) {
    sources = [{ base: root, pattern: "**/*", negated: false }, ...sources];
  } else if (compiler.root !== "none") {
    sources = [{ ...compiler.root, negated: false }, ...sources];
  }
  const scanner = new Scanner({ sources });
  return { compiler, scanner };
}

describe("development Tailwind sources", () => {
  it("limits automatic discovery to src and explicitly includes index.html", async () => {
    const css = fs.readFileSync(path.join(base, "global.css"), "utf8");
    const { compiler, scanner } = await prepare(css);
    expect(compiler.root).not.toBeNull();
    expect(compiler.root).not.toBe("none");
    if (!compiler.root || compiler.root === "none") {
      throw new Error("Expected an explicit source root");
    }
    expect(path.resolve(compiler.root.base, compiler.root.pattern)).toBe(
      path.join(root, "src")
    );
    expect(
      compiler.sources.some(
        (source) =>
          path.resolve(source.base, source.pattern) ===
          path.join(root, "index.html")
      )
    ).toBe(true);
    scanner.scan();
    expect(scanner.globs.length).toBeGreaterThan(0);
    expect(
      scanner.files.every((file) => {
        const relative = path.relative(root, file);
        return (
          relative === "index.html" || relative.startsWith(`src${path.sep}`)
        );
      })
    ).toBe(true);
  });

  it("preserves CSS generated by the previous repository-wide discovery", async () => {
    const css = fs.readFileSync(path.join(base, "global.css"), "utf8");
    const previous = css
      .replace(' source("../")', "")
      .replace('@source "../../index.html";', "")
      .replace('@source inline("lowercase !paused");', "");
    const current = await prepare(css);
    const baseline = await prepare(previous);
    expect(current.compiler.build(current.scanner.scan())).toBe(
      baseline.compiler.build(baseline.scanner.scan())
    );
  });
});
